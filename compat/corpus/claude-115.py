"""claude-115 - Modular cable tray installation: straight ladder sections, a tee junction,
a 90 degree vertical drop, wall brackets, splice plates and routed cable bundles.

Tray sections are generated by a parametric ladder builder and placed with object
matrices; the elbow rails are swept along an arc with a moving frame.
"""

import bpy
import bmesh
import math
import random
from mathutils import Vector, Matrix

random.seed(23)

# --------------------------------------------------------------- parameters
TRAY_W = 0.40         # inside width
RAIL_H = 0.10         # rail height
WEB_T = 0.007
FLANGE = 0.030
RUNG_PITCH = 0.25
Z_MAIN = 2.60         # upper tray centreline height
Z_LOWER = 2.05        # second tier
Y_TRAY = 0.52         # standoff from the wall face
WALL_Y = 0.0
BEND_R = 0.35


# --------------------------------------------------------------- utilities
def reset_scene():
    bpy.ops.wm.read_factory_settings(use_empty=True)
    bpy.context.scene.unit_settings.system = 'METRIC'


def make_material(name, color, metallic=0.0, rough=0.5):
    m = bpy.data.materials.new(name)
    m.use_nodes = True
    p = m.node_tree.nodes["Principled BSDF"]
    p.inputs["Base Color"].default_value = (color[0], color[1], color[2], 1.0)
    p.inputs["Metallic"].default_value = metallic
    p.inputs["Roughness"].default_value = rough
    return m


def new_object(name, verts, faces, mats=(), smooth=False):
    me = bpy.data.meshes.new(name)
    me.from_pydata(verts, [], faces)
    me.validate()
    me.update()
    for m in mats:
        me.materials.append(m)
    if smooth:
        for poly in me.polygons:
            poly.use_smooth = True
    ob = bpy.data.objects.new(name, me)
    bpy.context.collection.objects.link(ob)
    return ob


def recalc_normals(ob):
    bm = bmesh.new()
    bm.from_mesh(ob.data)
    bmesh.ops.recalc_face_normals(bm, faces=bm.faces)
    bm.to_mesh(ob.data)
    bm.free()
    ob.data.update()


BOX_FACES = ((0, 1, 3, 2), (4, 6, 7, 5), (0, 4, 5, 1),
             (2, 3, 7, 6), (0, 2, 6, 4), (1, 5, 7, 3))


def add_box(verts, faces, center, size, rot_z=0.0):
    mtx = Matrix.Translation(Vector(center)) @ Matrix.Rotation(rot_z, 4, 'Z')
    sx, sy, sz = size
    off = len(verts)
    for dx in (-0.5, 0.5):
        for dy in (-0.5, 0.5):
            for dz in (-0.5, 0.5):
                verts.append(tuple(mtx @ Vector((dx * sx, dy * sy, dz * sz))))
    for f in BOX_FACES:
        faces.append(tuple(off + i for i in f))


def add_beam(verts, faces, p0, p1, w, h, up=(0.0, 0.0, 1.0)):
    p0 = Vector(p0)
    p1 = Vector(p1)
    d = p1 - p0
    if d.length < 1e-9:
        return
    d.normalize()
    side = d.cross(Vector(up))
    if side.length < 1e-6:
        side = d.cross(Vector((1.0, 0.0, 0.0)))
    side.normalize()
    upv = side.cross(d).normalized()
    off = len(verts)
    for base in (p0, p1):
        for s, u in ((-1, -1), (-1, 1), (1, 1), (1, -1)):
            verts.append(tuple(base + side * (s * w * 0.5) + upv * (u * h * 0.5)))
    faces.append((off + 3, off + 2, off + 1, off + 0))
    faces.append((off + 4, off + 5, off + 6, off + 7))
    for i in range(4):
        j = (i + 1) % 4
        faces.append((off + i, off + 4 + i, off + 4 + j, off + j))


def add_cylinder(verts, faces, center, radius, height, segments=12, axis='Z'):
    off = len(verts)
    cx, cy, cz = center
    for h in (-0.5, 0.5):
        for s in range(segments):
            a = 2.0 * math.pi * s / segments
            u, w = radius * math.cos(a), radius * math.sin(a)
            d = h * height
            if axis == 'Z':
                verts.append((cx + u, cy + w, cz + d))
            elif axis == 'Y':
                verts.append((cx + u, cy + d, cz + w))
            else:
                verts.append((cx + d, cy + u, cz + w))
    for s in range(segments):
        s2 = (s + 1) % segments
        faces.append((off + s, off + s2, off + segments + s2, off + segments + s))
    faces.append(tuple(off + segments - 1 - s for s in range(segments)))
    faces.append(tuple(off + segments + s for s in range(segments)))


def prism(verts, faces, poly2d, span, axis, offset=0.0):
    """Extrude a closed 2D polygon by `span` along `axis` (X or Y), centred on offset."""
    off = len(verts)
    n = len(poly2d)
    for s in (-0.5, 0.5):
        for (a, b) in poly2d:
            if axis == 'X':
                verts.append((offset + s * span, a, b))
            else:
                verts.append((a, offset + s * span, b))
    for i in range(n):
        j = (i + 1) % n
        faces.append((off + i, off + j, off + n + j, off + n + i))
    faces.append(tuple(off + n - 1 - i for i in range(n)))
    faces.append(tuple(off + n + i for i in range(n)))


def prism_between(verts, faces, poly2d, a0, a1, axis):
    """Same as prism() but between two explicit coordinates along the axis."""
    off = len(verts)
    n = len(poly2d)
    for s in (a0, a1):
        for (a, b) in poly2d:
            if axis == 'X':
                verts.append((s, a, b))
            else:
                verts.append((a, s, b))
    for i in range(n):
        j = (i + 1) % n
        faces.append((off + i, off + j, off + n + j, off + n + i))
    faces.append(tuple(off + n - 1 - i for i in range(n)))
    faces.append(tuple(off + n + i for i in range(n)))


def sweep(verts, faces, path, prof, up_ref=(0.0, 0.0, 1.0), caps=True):
    """Sweep a closed 2D profile along a polyline using a side/normal frame."""
    path = [Vector(p) for p in path]
    n = len(prof)
    rings = []
    for i, p in enumerate(path):
        if i == 0:
            t = path[1] - path[0]
        elif i == len(path) - 1:
            t = path[-1] - path[-2]
        else:
            t = path[i + 1] - path[i - 1]
        t.normalize()
        side = t.cross(Vector(up_ref))
        if side.length < 1e-6:
            side = t.cross(Vector((1.0, 0.0, 0.0)))
        side.normalize()
        nrm = side.cross(t).normalized()
        ring = []
        for (a, b) in prof:
            ring.append(len(verts))
            verts.append(tuple(p + side * a + nrm * b))
        rings.append(ring)
    for i in range(len(rings) - 1):
        A, B = rings[i], rings[i + 1]
        for j in range(n):
            j2 = (j + 1) % n
            faces.append((A[j], A[j2], B[j2], B[j]))
    if caps:
        faces.append(tuple(reversed(rings[0])))
        faces.append(tuple(rings[-1]))


# --------------------------------------------------------------- tray builders
def rail_profile():
    """C-channel rail outline in (across, up); flanges open toward -across."""
    t = WEB_T
    h = RAIL_H
    fl = FLANGE
    return [(0.0, -h * 0.5), (0.0, h * 0.5), (-fl, h * 0.5), (-fl, h * 0.5 - t),
            (-t, h * 0.5 - t), (-t, -h * 0.5 + t), (-fl, -h * 0.5 + t),
            (-fl, -h * 0.5)]


PROF = rail_profile()


def side_rail_poly(sgn):
    """Rail outline in (Y, Z) for the -Y or +Y rail, flanges facing inboard."""
    return [(sgn * (TRAY_W * 0.5) + sgn * a, b) for (a, b) in PROF]


def make_tray_mesh(name, length, mat, splice=True):
    """Ladder tray running along local X, centred at the origin."""
    v, f = [], []
    for sgn in (-1.0, 1.0):
        prism(v, f, side_rail_poly(sgn), length, 'X')
    n_rungs = max(2, int(length / RUNG_PITCH))
    for k in range(n_rungs + 1):
        x = -length * 0.5 + length * k / n_rungs
        add_box(v, f, (x, 0.0, -RAIL_H * 0.5 + 0.012),
                (0.030, TRAY_W - 2.0 * WEB_T, 0.009))
    if splice:
        for sx in (-1.0, 1.0):
            for sy in (-1.0, 1.0):
                add_box(v, f, (sx * (length * 0.5 - 0.05), sy * (TRAY_W * 0.5 + 0.010), 0.0),
                        (0.14, 0.006, RAIL_H - 0.024))
                for bx in (-0.04, 0.04):
                    add_cylinder(v, f, (sx * (length * 0.5 - 0.05) + bx,
                                        sy * (TRAY_W * 0.5 + 0.016), 0.0),
                                 0.010, 0.012, segments=8, axis='Y')
    ob = new_object(name, v, f, [mat])
    recalc_normals(ob)
    return ob


def make_bracket_mesh(name, mat):
    """Cantilever wall bracket: wall plate, tapered arm, gusset and hardware."""
    v, f = [], []
    add_box(v, f, (0.0, 0.035, 0.0), (0.09, 0.07, 0.34))              # wall plate
    arm = [(0.07, 0.03), (Y_TRAY + 0.16, 0.03), (Y_TRAY + 0.16, -0.03), (0.07, -0.075)]
    prism(v, f, arm, 0.055, 'X')                                      # tapered arm
    gus = [(0.07, -0.10), (0.40, -0.10), (0.07, -0.30)]
    prism(v, f, gus, 0.006, 'X')                                      # gusset
    for dz in (-0.12, 0.12):
        add_cylinder(v, f, (0.0, 0.012, dz), 0.014, 0.05, segments=10, axis='Y')
        add_cylinder(v, f, (0.0, -0.02, dz), 0.020, 0.02, segments=8, axis='Y')
    ob = new_object(name, v, f, [mat])
    recalc_normals(ob)
    return ob


def cable(name, pts, radius, mat, res=4):
    cu = bpy.data.curves.new(name, 'CURVE')
    cu.dimensions = '3D'
    sp = cu.splines.new('POLY')
    sp.points.add(len(pts) - 1)
    for i, p in enumerate(pts):
        sp.points[i].co = (p[0], p[1], p[2], 1.0)
    cu.bevel_depth = radius
    cu.bevel_resolution = res
    cu.use_fill_caps = True
    cu.resolution_u = 4
    cu.materials.append(mat)
    ob = bpy.data.objects.new(name, cu)
    bpy.context.collection.objects.link(ob)
    return ob


