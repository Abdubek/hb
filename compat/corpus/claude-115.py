reset_scene()

mat_galv = make_material("Galvanised Steel", (0.62, 0.64, 0.66), metallic=1.0, rough=0.42)
mat_galv2 = make_material("Bracket Steel", (0.52, 0.54, 0.57), metallic=1.0, rough=0.50)
mat_wall = make_material("Concrete Wall", (0.56, 0.55, 0.52), rough=0.85)
mat_floor = make_material("Plant Floor", (0.20, 0.21, 0.22), rough=0.70)
mat_label = make_material("Tray Label", (0.90, 0.72, 0.10), rough=0.45)
cable_mats = [
    make_material("Cable Black", (0.03, 0.03, 0.035), rough=0.55),
    make_material("Cable Grey", (0.30, 0.31, 0.33), rough=0.55),
    make_material("Cable Blue", (0.05, 0.14, 0.42), rough=0.50),
    make_material("Cable Orange", (0.62, 0.26, 0.04), rough=0.50),
]

# --- wall and floor --------------------------------------------------------
v, f = [], []
add_box(v, f, (0.0, -0.15, 2.0), (9.0, 0.30, 4.0))
wall = new_object("Wall", v, f, [mat_wall])
recalc_normals(wall)
new_object("Floor", [(-5.5, -0.3, 0.0), (5.5, -0.3, 0.0), (5.5, 5.5, 0.0), (-5.5, 5.5, 0.0)],
           [(0, 1, 2, 3)], [mat_floor])

# --- main run: straight modules either side of a tee junction --------------
X_TEE = 0.60
TEE_L = 0.60
tray_objects = []
for (name, x0, x1) in (("Tray_Main_A", -3.60, X_TEE - TEE_L * 0.5),
                       ("Tray_Main_B", X_TEE + TEE_L * 0.5, 3.30)):
    ob = make_tray_mesh(name, x1 - x0, mat_galv)
    ob.location = ((x0 + x1) * 0.5, Y_TRAY, Z_MAIN)
    tray_objects.append(ob)

# lower tier straight run (same module type)
lower = make_tray_mesh("Tray_Lower", 6.4, mat_galv)
lower.location = (-0.30, Y_TRAY, Z_LOWER)
tray_objects.append(lower)

# --- tee junction fitting --------------------------------------------------
v, f = [], []
# wall-side rail runs through; outer rail is cut open for the branch
prism(v, f, side_rail_poly(-1.0), TEE_L, 'X')
for sgn in (-1.0, 1.0):
    prism_between(v, f, side_rail_poly(1.0),
                  sgn * TEE_L * 0.5, sgn * (TRAY_W * 0.5 + 0.03), 'X')
# branch rails leaving toward +Y
for sgn in (-1.0, 1.0):
    poly_yz = [(sgn * (TRAY_W * 0.5) + sgn * a, b) for (a, b) in PROF]
    off = len(v)
    n = len(poly_yz)
    for y in (TRAY_W * 0.5, TRAY_W * 0.5 + 0.30):
        for (x_local, z) in poly_yz:
            v.append((x_local, y, z))
    for i in range(n):
        j = (i + 1) % n
        f.append((off + i, off + j, off + n + j, off + n + i))
    f.append(tuple(off + n - 1 - i for i in range(n)))
    f.append(tuple(off + n + i for i in range(n)))
# bed plates and corner gussets
add_box(v, f, (0.0, 0.0, -RAIL_H * 0.5 + 0.010), (TEE_L, TRAY_W, 0.010))
add_box(v, f, (0.0, TRAY_W * 0.5 + 0.15, -RAIL_H * 0.5 + 0.010), (TRAY_W, 0.30, 0.010))
for sx in (-1.0, 1.0):
    add_box(v, f, (sx * (TRAY_W * 0.5 - 0.02), TRAY_W * 0.5 - 0.02, 0.0),
            (0.10, 0.10, RAIL_H * 0.8), rot_z=sx * math.radians(45.0))
tee = new_object("Tray_Tee_Junction", v, f, [mat_galv])
recalc_normals(tee)
tee.location = (X_TEE, Y_TRAY, Z_MAIN)

# --- branch run heading away from the wall ---------------------------------
branch = make_tray_mesh("Tray_Branch", 2.10, mat_galv)
branch.matrix_world = (Matrix.Translation(Vector((X_TEE, Y_TRAY + 0.30 + 1.05, Z_MAIN)))
                       @ Matrix.Rotation(math.radians(90.0), 4, 'Z'))
tray_objects.append(branch)

# --- 90 degree elbow turning the main run down at +X -----------------------
X_BEND = 3.30
arc_pts = []
for k in range(13):
    a = math.pi * 0.5 * k / 12
    arc_pts.append(Vector((X_BEND + BEND_R * math.sin(a), Y_TRAY,
                           Z_MAIN - BEND_R + BEND_R * math.cos(a))))
v, f = [], []
for sgn in (-1.0, 1.0):
    sweep(v, f, arc_pts, side_rail_poly(sgn), up_ref=(0.0, 1.0, 0.0))
for k in range(0, 13, 2):
    p = arc_pts[k]
    a = math.pi * 0.5 * k / 12
    nx, nz = math.sin(a), math.cos(a)
    inner = Vector((p.x - nx * (RAIL_H * 0.5 - 0.012), p.y,
                    p.z - nz * (RAIL_H * 0.5 - 0.012)))
    add_beam(v, f, inner - Vector((0.0, TRAY_W * 0.5 - WEB_T, 0.0)),
             inner + Vector((0.0, TRAY_W * 0.5 - WEB_T, 0.0)), 0.030, 0.009,
             up=(nx, 0.0, nz))
elbow = new_object("Tray_Elbow_90", v, f, [mat_galv], smooth=True)
recalc_normals(elbow)

z_drop_top = Z_MAIN - BEND_R
z_drop_bot = 0.95
drop = make_tray_mesh("Tray_Drop", z_drop_top - z_drop_bot, mat_galv)
drop.matrix_world = (Matrix.Translation(Vector((X_BEND + BEND_R, Y_TRAY,
                                                (z_drop_top + z_drop_bot) * 0.5)))
                     @ Matrix.Rotation(math.radians(90.0), 4, 'Y'))
tray_objects.append(drop)

# --- brackets (linked duplicates of one module) ----------------------------
bracket_proto = make_bracket_mesh("Bracket", mat_galv2)
bracket_mesh = bracket_proto.data
bpy.context.collection.objects.unlink(bracket_proto)

n_brackets = 0
for x in (-3.30, -2.10, -0.90, 0.60, 1.80, 3.00):
    for z in (Z_MAIN, Z_LOWER):
        if z == Z_LOWER and (x > 2.9 or x < -3.2):
            continue
        ob = bpy.data.objects.new("Bracket_%+0.2f_%0.2f" % (x, z), bracket_mesh)
        bpy.context.collection.objects.link(ob)
        ob.matrix_world = Matrix.Translation(Vector((x, WALL_Y, z - RAIL_H * 0.5 - 0.03)))
        n_brackets += 1

# drop-run wall clamps
v, f = [], []
for z in (2.00, 1.55, 1.10):
    add_box(v, f, (X_BEND + BEND_R, Y_TRAY * 0.5, z), (0.05, Y_TRAY, 0.06))
    add_box(v, f, (X_BEND + BEND_R, 0.03, z), (0.12, 0.06, 0.20))
clamps = new_object("Drop_Clamps", v, f, [mat_galv2])
recalc_normals(clamps)

# --- identification labels -------------------------------------------------
v, f = [], []
for x in (-2.6, -0.2, 2.2):
    add_box(v, f, (x, Y_TRAY + TRAY_W * 0.5 + 0.014, Z_MAIN), (0.16, 0.004, 0.05))
for x in (-2.0, 1.0):
    add_box(v, f, (x, Y_TRAY + TRAY_W * 0.5 + 0.014, Z_LOWER), (0.16, 0.004, 0.05))
labels = new_object("Tray_Labels", v, f, [mat_label])
recalc_normals(labels)

# --- cable bundles ---------------------------------------------------------
n_cables = 0
lanes = [-0.14, -0.075, -0.01, 0.055, 0.12]
for i, dy in enumerate(lanes):
    r = 0.020 + 0.006 * (i % 3)
    z_base = Z_MAIN - RAIL_H * 0.5 + 0.022 + r
    pts = []
    xs = [-3.6 + 0.30 * k for k in range(int(6.9 / 0.30) + 1)]
    for x in xs:
        sag = 0.010 * math.sin((x + 3.6) * math.pi / 1.2) - 0.004
        pts.append((x, Y_TRAY + dy, z_base + sag))
    if i % 2 == 0:                      # these lanes continue round the elbow
        for k in range(1, 13):
            a = math.pi * 0.5 * k / 12
            rr = BEND_R - (RAIL_H * 0.5 - 0.022 - r)
            pts.append((X_BEND + rr * math.sin(a), Y_TRAY + dy,
                        Z_MAIN - BEND_R + rr * math.cos(a)))
        pts.append((X_BEND + BEND_R - (RAIL_H * 0.5 - 0.022 - r), Y_TRAY + dy, 1.05))
    cable("Cable_Main_%d" % i, pts, r, cable_mats[i % len(cable_mats)])
    n_cables += 1

# branch cables turning at the tee
for i, dy in enumerate(lanes[:3]):
    r = 0.018 + 0.005 * i
    z_base = Z_MAIN - RAIL_H * 0.5 + 0.022 + r
    pts = [(-3.4, Y_TRAY + dy, z_base), (X_TEE - 0.45, Y_TRAY + dy, z_base)]
    for k in range(1, 9):
        a = (k / 8.0) * math.pi * 0.5
        pts.append((X_TEE - 0.45 + 0.45 * math.sin(a),
                    Y_TRAY + dy + 0.45 * (1.0 - math.cos(a)), z_base))
    for y in (Y_TRAY + 0.55, Y_TRAY + 1.20, Y_TRAY + 1.85, Y_TRAY + 2.35):
        pts.append((X_TEE + dy, y, z_base))
    cable("Cable_Branch_%d" % i, pts, r, cable_mats[(i + 2) % len(cable_mats)])
    n_cables += 1

# lower tier cables
for i in range(4):
    dy = -0.13 + 0.085 * i
    r = 0.024 + 0.004 * (i % 2)
    z_base = Z_LOWER - RAIL_H * 0.5 + 0.022 + r
    pts = [(-3.45 + 0.35 * k, Y_TRAY + dy,
            z_base + 0.008 * math.sin(k * 0.7)) for k in range(19)]
    cable("Cable_Lower_%d" % i, pts, r, cable_mats[(i + 1) % len(cable_mats)])
    n_cables += 1

# cable ties at intervals
v, f = [], []
